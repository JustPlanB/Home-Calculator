/** آیکن به‌صورت عنصر DOM: icon('plus') — اندازه با font-size والد یا پارامتر px */
export function icon(name, px) {
  const body = ICONS[name];
  if (!body) throw new Error('آیکن ناشناخته: ' + name);
  const el = h('span', { class: 'k-ico', 'aria-hidden': 'true', html: `<svg viewBox="0 0 24 24" focusable="false">${body}</svg>` });
  if (px) el.style.fontSize = px + 'px';
  return el;
}

/** دیسک آیکن (کاشی): icon در دایره‌ی سفید — هم‌سبک حساب‌کتاب */
export function disc(name, { danger = false, small = false } = {}) {
  return h('span', { class: 'k-disc' + (danger ? ' k-disc--danger' : '') + (small ? ' k-disc--sm' : '') }, icon(name));
}

